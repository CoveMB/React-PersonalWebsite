import { useEffect, useRef } from 'react';

// Only presentation-level Markdown parsing: no role evaluation, factual
// matching, evidence selection, or claim rewriting occurs in this component.
const renderInlineEmphasis = (content) => content.split(/(\*\*[^*]+\*\*)/g).map((part, index) =>
  part.startsWith('**') && part.endsWith('**') && part.length > 4
    ? <strong key={index}>{part.slice(2, -2)}</strong>
    : part);

function ModelText({ text }) {
  // Group adjacent model-written bullets into semantic lists without changing
  // any of their words, categories, or truth status.
  const blocks = [];
  let pendingBullets = [];
  const flushBullets = () => {
    if (pendingBullets.length) {
      blocks.push(<ul key={`list-${blocks.length}`} className="roleFitAIModelBulletList">
        {pendingBullets.map(({ value, lineNumber }) => <li key={lineNumber} className="roleFitAIModelBullet">{renderInlineEmphasis(value)}</li>)}
      </ul>);
      pendingBullets = [];
    }
  };
  for (const [index, line] of text.split(/\r?\n/).entries()) {
    const cleaned = line.trim();
    if (!cleaned) { flushBullets(); continue; }
    const bullet = /^(?:[-*•]|\d+[.)])\s+(.+)$/.exec(cleaned);
    if (bullet) { pendingBullets.push({ value: bullet[1], lineNumber: index }); continue; }
    flushBullets();
    const heading = /^#{1,6}\s+(.+)$/.exec(cleaned) || /^(?:\*\*)?(Directly demonstrated|Transferable experience|Not established)\s*:?(?:\*\*)?$/i.exec(cleaned);
    if (heading) {
      blocks.push(<h4 key={index} className="roleFitAIModelHeading">{renderInlineEmphasis(heading[1])}</h4>);
    } else {
      blocks.push(<p key={index} className="roleFitAIModelLine">{renderInlineEmphasis(cleaned)}</p>);
    }
  }
  flushBullets();
  return <div className="roleFitAIModelText" aria-label="Unverified words generated by the local model">{blocks}</div>;
}

export default function RoleFitAIReport({ assessment, status, modelId, progress, analysisId }) {
  const headingRef = useRef(null);
  useEffect(() => { headingRef.current?.focus(); }, [analysisId]);
  const isReady = status === 'ready' && assessment?.kind === 'generated' && Boolean(assessment?.text);

  return (
    <article className="aiPart roleFitResultCard roleFitAIResultCard" aria-labelledby="role-fit-ai-heading">
      <p className="roleFitResultEyebrow">Experimental on-device language model</p>
      <h3 id="role-fit-ai-heading" className="roleFitReportTitle" ref={headingRef} tabIndex={-1}>AI assessment</h3>
      <p className="roleFitAIWarning">
        <strong>AI-generated, unverified interpretation.</strong> This small local model can invent or misclassify experience. Its statements are <strong>not source-checked</strong>; compare them with the published résumé and the independent mechanical assessment below.
      </p>
      {modelId && status === 'ready' ? <p className="roleFitAIModelLabel">Model: {modelId}</p> : null}
      {status === 'running' ? (
        <p className="roleFitAIProgress" role="status" aria-live="polite">
          {progress || 'The local AI model is preparing its own assessment…'}
        </p>
      ) : null}
      {status === 'unavailable' ? (
        <p className="roleFitAIProgress" role="status">
          This browser cannot run the local AI model (WebGPU and Worker support required). No AI assessment was generated. The independent mechanical assessment is below.
        </p>
      ) : null}
      {status === 'failed' ? (
        <p className="roleFitAIProgress" role="status">
          The local AI model did not finish. No AI assessment was generated. The mechanical assessment below remains available.
        </p>
      ) : null}
      {status === 'empty' || (status === 'ready' && assessment?.kind === 'empty') ? (
        <p className="roleFitAIProgress" role="status">The local AI model returned no text. No AI assessment is available; the mechanical comparison is below.</p>
      ) : null}
      {isReady ? <ModelText text={assessment.text} /> : null}
      {assessment?.postingTruncated && status === 'ready' ? (
        <p className="roleFitAIWarningDetail">The local AI reviewed only the first 5,000 characters of this posting due to model-context limits. The mechanical assessment below analyzes the full pasted text.</p>
      ) : null}
      {assessment?.outputTruncated && status === 'ready' ? (
        <p className="roleFitAIWarningDetail">The model returned more text than this card can safely display; its output has been shortened.</p>
      ) : null}
      {assessment?.presentationAdjusted && status === 'ready' ? (
        <p className="roleFitAIWarningDetail">Repeated headings or excessive model-written bullets were hidden for readability. The original unverified output is available under diagnostics. No claims were inserted or reclassified.</p>
      ) : null}
      {assessment?.missingSections?.length > 0 && isReady ? (
        <p className="roleFitAIWarningDetail">This model response omitted one or more requested sections ({assessment.missingSections.join(', ')}). No missing conclusions were generated by the site.</p>
      ) : null}
      {assessment?.outputLimitReached && status === 'ready' ? (
        <p className="roleFitAIWarningDetail">The local model reached its generation limit. Its response may be unfinished; compare with the mechanical assessment below.</p>
      ) : null}
      {status === 'ready' && assessment?.kind === 'unstructured' ? (
        <p className="roleFitAIProgress" role="status">The local model returned output that could not be formatted as a recruiter assessment. Its unverified original response is available under diagnostics; nothing was substituted.</p>
      ) : null}
      {status === 'ready' && assessment?.original && (assessment.kind === 'unstructured' || assessment.original !== assessment.text) ? (
        <details className="roleFitInventory roleFitAIDetails">
          <summary>Original local-model response (unverified)</summary>
          <p>Diagnostic text written by the model. This is not verified candidate experience.</p>
          <pre>{assessment.original}</pre>
        </details>
      ) : null}
    </article>
  );
}
